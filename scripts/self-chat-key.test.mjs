import {test} from 'node:test';
import assert from 'node:assert/strict';
import {installMockLibWrapper} from './lib-wrapper-fixture.mjs';
import {registerSelfChatKey,selfChatHeld} from '../dist/scripts/self-chat-key.js';

test('hold Self preserves saved mode, captures new-message audiences and clears on release/focus loss',async()=>{
  installMockLibWrapper();const hooks={},events={},docEvents={},created=[],dice=[];let config,label;
  globalThis.foundry={utils:{deepClone:structuredClone}};
  globalThis.Hooks={once:(key,fn)=>hooks[key]=fn,on:(key,fn)=>hooks[key]=fn};
  globalThis.window={addEventListener:(key,fn)=>events[key]=fn};
  globalThis.document={hidden:false,querySelector:()=>null,getElementById:()=>label,createElement:()=>({dataset:{},style:{},setAttribute(){},remove(){label=undefined;}}),body:{append:node=>label=node},addEventListener:(key,fn)=>docEvents[key]=fn};
  globalThis.game={user:{id:'owner'},keybindings:{register:(_m,_k,value)=>config=value,get:()=>config.editable},settings:{get:(_m,key)=>key==='rollMode'?'gmroll':42},dice3d:{showForRoll:(...args)=>dice.push(args)}};
  globalThis.CONFIG={ChatMessage:{documentClass:{createDocuments:async(rows,options)=>{await Promise.resolve();created.push({rows,options});return rows;}}}};
  registerSelfChatKey();hooks.ready();
  assert.deepEqual(config.editable,[{key:'AltLeft'},{key:'AltRight'}]);assert.equal(config.restricted,false);
  assert.equal(game.settings.get('core','rollMode'),'gmroll');
  const down=code=>events.keydown({code,altKey:true,ctrlKey:false,shiftKey:false});
  down('AltLeft');assert.equal(selfChatHeld(),true);assert.equal(game.settings.get('core','rollMode'),'selfroll');
  assert.equal(game.settings.get('other','rollMode'),'gmroll');assert.equal(game.settings.get('core','other'),42);
  assert.equal(label.textContent,'SELF chat — key held');
  const original={content:'roll',whisper:['gm'],blind:true},options={rollMode:'blindroll'};
  const pending=CONFIG.ChatMessage.documentClass.createDocuments([original],options);
  game.dice3d.showForRoll('dice',game.user,true,null,true);
  events.keyup({code:'AltLeft'});await pending;
  assert.deepEqual(created[0],{rows:[{content:'roll',whisper:['owner'],blind:false}],options:{rollMode:'selfroll'}});
  assert.deepEqual(original,{content:'roll',whisper:['gm'],blind:true});assert.equal(options.rollMode,'blindroll');
  assert.deepEqual(dice[0],['dice',game.user,false,['owner'],false]);
  assert.equal(game.settings.get('core','rollMode'),'gmroll');assert.equal(label,undefined);
  down('AltLeft');down('AltRight');events.keyup({code:'AltLeft'});assert.equal(selfChatHeld(),true);
  events.blur();assert.equal(selfChatHeld(),false);
  down('AltLeft');document.hidden=true;docEvents.visibilitychange();assert.equal(selfChatHeld(),false);
  config.editable=[{key:'KeyQ'}];down('AltLeft');assert.equal(selfChatHeld(),false);down('KeyQ');assert.equal(selfChatHeld(),true);
  const updates=[];hooks.preCreateChatMessage({updateSource:data=>updates.push(data)},null,null,'other');assert.equal(updates.length,0);
  hooks.preCreateChatMessage({updateSource:data=>updates.push(data)},null,null,'owner');assert.deepEqual(updates,[{whisper:['owner'],blind:false}]);
  events.blur();await CONFIG.ChatMessage.documentClass.createDocuments([original],options);assert.deepEqual(created[1],{rows:[original],options});
  const attack={content:'<div data-pneuma-self-user="owner">attack</div>',flags:{'pneuma-combattools':{exchange:{rollMode:'roll'}}}};
  await CONFIG.ChatMessage.documentClass.createDocuments([attack,{content:'unrelated'}],{});
  assert.deepEqual(created[2].rows[0].whisper,['owner']);assert.equal(created[2].rows[0].blind,false);
  assert.equal(created[2].rows[0].flags['pneuma-combattools'].exchange.rollMode,'selfroll');
  assert.equal(attack.flags['pneuma-combattools'].exchange.rollMode,'roll');assert.equal(created[2].rows[1].whisper,undefined);
  hooks.preCreateChatMessage({content:attack.content,updateSource:data=>updates.push(data)},null,null,'gm');
  assert.deepEqual(updates.at(-1),{whisper:['owner'],blind:false});
});
